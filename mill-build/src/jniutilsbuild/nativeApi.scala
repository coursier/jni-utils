package jniutilsbuild

import mill.*, scalalib.*
import mill.api.BuildCtx

/**
 * Generates the boilerplate around the native methods of the library, from the single list
 * in [[NativeApiMethods.methods]]:
 * - the `NativeApi` implementations (`DefaultNativeApi`, and its copies in the packages of the
 *   projects shading this library), with their `static native` methods and the public methods
 *   delegating to them,
 * - the JNI headers of these classes,
 * - the C functions binding the native methods of the copies to the ones of `DefaultNativeApi`.
 *
 * The copies are checked in (see [[CheckedInNativeApi]]), the rest is generated under `out/`.
 *
 * The abstract methods of `NativeApi` itself are hand-written: as the generated methods are
 * marked with `@Override`, and the generated classes are concrete, javac fails if the two
 * don't match.
 */
object NativeApiGen {

  sealed abstract class JType(val java: String, val jni: String, val descriptor: String)
  object JType {
    case object Void    extends JType("void", "void", "V")
    case object Boolean extends JType("boolean", "jboolean", "Z")
    case object Int     extends JType("int", "jint", "I")
    case object Long    extends JType("long", "jlong", "J")
    case object String  extends JType("String", "jstring", "Ljava/lang/String;")
  }

  /**
   * A method of `NativeApi`, implemented by a `static native` method named like it with a
   * `Native` suffix, whose C implementation is in `windows-jni-utils/src/main/c`.
   */
  final case class Method(name: String, params: Seq[(String, JType)], ret: JType) {
    def nativeName: String = name + "Native"
    def descriptor: String = params.map(_._2.descriptor).mkString("(", "", ")") + ret.descriptor
  }

  /**
   * A class implementing `NativeApi` with native methods.
   *
   * @param relocated whether this is a copy of `DefaultNativeApi` for a project shading this
   *                  library, whose native methods are bound to the ones of `DefaultNativeApi`
   * @param dllVariant the variant this class passes to `LoadWindowsLibrary.ensureInitialized`,
   *                   so that the DLL is loaded from a file of its own (empty for the default name)
   */
  final case class Impl(pkg: String, className: String, relocated: Boolean, dllVariant: String) {
    def fullName: String = s"$pkg.$className"
    def jniName: String = fullName.split('.').map(mangle).mkString("_")
    def headerName: String = s"$jniName.h"
    def cFunction(m: Method): String = s"Java_${jniName}_${mangle(m.nativeName)}"
  }

  val default     = Impl("coursier.jniutils", "DefaultNativeApi", relocated = false, dllVariant = "")
  val bootstrap   = Impl("coursier.bootstrap.launcher.jniutils", "BootstrapNativeApi", relocated = true, dllVariant = "bootstrap")
  val lmcoursier  = Impl("lmcoursier.internal.jniutils", "LmNativeApi", relocated = true, dllVariant = "lmcoursier")
  val coursierapi = Impl("coursierapi.internal.jniutils", "ApiInternalNativeApi", relocated = true, dllVariant = "coursierapi")

  val impls: Seq[Impl] = Seq(default, bootstrap, lmcoursier, coursierapi)

  // JNI name mangling. Overloaded native methods would need the long form of the names,
  // with the argument signature appended - that's not supported (and checked below).
  private def mangle(name: String): String =
    name.flatMap {
      case '_' => "_1"
      case ';' => "_2"
      case '[' => "_3"
      case c if c < 128 && c.isLetterOrDigit => c.toString
      case c => f"_0${c.toInt}%04x"
    }

  private def methods: Seq[Method] = {
    val methods0 = NativeApiMethods.methods
    val duplicates = methods0.groupBy(_.nativeName).collect { case (n, l) if l.lengthCompare(1) > 0 => n }
    assert(duplicates.isEmpty, s"Overloaded native methods aren't supported: ${duplicates.mkString(", ")}")
    assert(methods0.forall(_.params.forall(_._2 != JType.Void)))
    methods0
  }

  private def generatedBy = "Generated by the build from mill-build/src/jniutilsbuild/nativeApiMethods.scala - don't edit"

  def javaSource(impl: Impl): String = {
    val b = new StringBuilder
    b ++= s"// $generatedBy\n"
    b ++= s"package ${impl.pkg};\n\n"
    if (impl.relocated)
      b ++= "import coursier.jniutils.LoadWindowsLibrary;\nimport coursier.jniutils.NativeApi;\n\n"
    b ++= s"public final class ${impl.className} extends NativeApi {\n\n"
    for (m <- methods) {
      val params = m.params.map { case (n, t) => s"${t.java} $n" }.mkString(", ")
      b ++= s"    static native ${m.ret.java} ${m.nativeName}($params);\n"
    }
    for (m <- methods) {
      val params = m.params.map { case (n, t) => s"${t.java} $n" }.mkString(", ")
      val args = m.params.map(_._1).mkString(", ")
      val ret = if (m.ret == JType.Void) "" else "return "
      b ++= "\n"
      b ++= "    @Override\n"
      b ++= s"    public ${m.ret.java} ${m.name}($params) {\n"
      b ++= s"        $ret${m.nativeName}($args);\n"
      b ++= "    }\n"
    }
    val variantArg = if (impl.dllVariant.isEmpty) "" else "\"" + impl.dllVariant + "\""
    b ++= "\n"
    b ++= "    static {\n"
    b ++= s"        LoadWindowsLibrary.ensureInitialized($variantArg);\n"
    b ++= "    }\n"
    if (impl.relocated) {
      b ++= "\n"
      b ++= "    public static void setup() {\n"
      b ++= s"        NativeApi.set(new ${impl.className}());\n"
      b ++= "    }\n"
    }
    b ++= "}\n"
    b.result()
  }

  // Same content as what javac -h generates
  def header(impl: Impl): String = {
    val b = new StringBuilder
    b ++= "/* DO NOT EDIT THIS FILE - it is machine generated */\n"
    b ++= "#include <jni.h>\n"
    b ++= s"/* Header for class ${impl.jniName} */\n\n"
    b ++= s"#ifndef _Included_${impl.jniName}\n"
    b ++= s"#define _Included_${impl.jniName}\n"
    b ++= "#ifdef __cplusplus\n"
    b ++= "extern \"C\" {\n"
    b ++= "#endif\n"
    for (m <- methods) {
      b ++= "/*\n"
      b ++= s" * Class:     ${impl.jniName}\n"
      b ++= s" * Method:    ${m.nativeName}\n"
      b ++= s" * Signature: ${m.descriptor}\n"
      b ++= " */\n"
      b ++= s"JNIEXPORT ${m.ret.jni} JNICALL ${impl.cFunction(m)}\n"
      b ++= s"  (${("JNIEnv *" +: "jclass" +: m.params.map(_._2.jni)).mkString(", ")});\n\n"
    }
    b ++= "#ifdef __cplusplus\n"
    b ++= "}\n"
    b ++= "#endif\n"
    b ++= "#endif\n"
    b.result()
  }

  def forwarders(impl: Impl): String = {
    assert(impl.relocated)
    val b = new StringBuilder
    b ++= s"/* $generatedBy */\n\n"
    b ++= s"#include \"${impl.headerName}\"\n"
    b ++= s"#include \"${default.headerName}\"\n"
    for (m <- methods) {
      val params = ("JNIEnv *env" +: "jclass class" +: m.params.map { case (n, t) => s"${t.jni} $n" }).mkString(", ")
      val args = ("env" +: "class" +: m.params.map(_._1)).mkString(", ")
      val ret = if (m.ret == JType.Void) "" else "return "
      b ++= "\n"
      b ++= s"JNIEXPORT ${m.ret.jni} JNICALL ${impl.cFunction(m)}\n"
      b ++= s"  ($params) {\n"
      b ++= s"  $ret${default.cFunction(m)}($args);\n"
      b ++= "}\n"
    }
    b.result()
  }

  /** Writes the Java source of impl under dir, and returns its path */
  def writeJava(dir: os.Path, impl: Impl): os.Path = {
    val f = dir / os.SubPath(impl.pkg.replace('.', '/')) / s"${impl.className}.java"
    os.write.over(f, javaSource(impl), createFolders = true)
    f
  }

  /** Writes the headers of all the implementations, and the C forwarders of the relocated ones, in dir */
  def writeC(dir: os.Path): Unit =
    for (impl <- impls) {
      os.write.over(dir / impl.headerName, header(impl), createFolders = true)
      if (impl.relocated)
        os.write.over(dir / s"${impl.jniName}.c", forwarders(impl), createFolders = true)
    }
}

/** A module whose sources include a generated `NativeApi` implementation */
trait GeneratedNativeApi extends JavaModule {
  def nativeApiImpl: NativeApiGen.Impl
  def generatedSources = Task {
    super.generatedSources() ++ Seq(PathRef(NativeApiGen.writeJava(Task.dest, nativeApiImpl)))
  }
}

/**
 * A module whose `NativeApi` implementation is generated, but checked in under `src/main/java`,
 * so that it can be compiled from the checked out sources alone.
 *
 * `generateNativeApi` (re-)writes it there, and `checkNativeApi` fails if it's not up-to-date.
 */
trait CheckedInNativeApi extends JavaModule {
  def nativeApiImpl: NativeApiGen.Impl

  private def nativeApiSubPath: os.SubPath =
    os.sub / "src/main/java" / os.SubPath(nativeApiImpl.pkg.replace('.', '/')) / s"${nativeApiImpl.className}.java"

  def nativeApiSource = Task.Source(nativeApiSubPath)

  /** Writes the `NativeApi` implementation of this module under `src/main/java` */
  def generateNativeApi() = Task.Command {
    val dir = moduleDir / "src/main/java"
    val f = BuildCtx.withFilesystemCheckerDisabled {
      NativeApiGen.writeJava(dir, nativeApiImpl)
    }
    System.err.println(s"Wrote ${f.relativeTo(BuildCtx.workspaceRoot)}")
    PathRef(f)
  }

  /** Fails if the `NativeApi` implementation under `src/main/java` isn't the one the build generates */
  def checkNativeApi() = Task.Command {
    val f = nativeApiSource().path
    val expected = NativeApiGen.javaSource(nativeApiImpl)
    val upToDate = os.isFile(f) && os.read(f) == expected
    if (!upToDate) {
      val what = if (os.exists(f)) "is not up-to-date" else "doesn't exist"
      Task.fail(
        s"${f.relativeTo(BuildCtx.workspaceRoot)} $what, run './mill __.generateNativeApi' to update it"
      )
    }
  }
}
